// Card paina unna visual: image unte image, lekapothe gradient + pedda number
function CardVisual({ p }) {
    if (p.image) {
        return <img src={p.image} alt={p.title} className="h-full w-full object-cover" />;
    }
    return (
        <div
            className="relative flex h-full w-full items-center justify-center overflow-hidden"
            style={{ background: `linear-gradient(135deg, ${p.hue[0]}55, ${p.hue[1]}22 60%, #060606)` }}
        >
            <span className="outline-letter select-none text-[110px] font-extrabold leading-none tracking-tighter opacity-70">
                {p.id}
            </span>
            <span className="absolute bottom-3 right-4 text-3xl">{p.icon}</span>
        </div>
    );
}

// Modal lo repeat ayye section (title + list)
function Block({ title, items, ordered }) {
    return items.length ? (
        <div className="mt-6">
            <h4 className="mb-2 text-sm font-semibold uppercase tracking-widest text-sig">{title}</h4>
            <ul className="space-y-2 text-[15px] leading-relaxed text-mute">
                {items.map((t, i) => (
                    <li key={t} className="flex gap-3">
                        <span className="mt-0.5 shrink-0 text-sig">{ordered ? `${i + 1}.` : "•"}</span>
                        <span>{t}</span>
                    </li>
                ))}
            </ul>
        </div>
    ) : null;
}

function Modal({ p, onClose }) {
    // Esc nokkithe close, modal open unnappudu background scroll apeyali
    useEffect(() => {
        const onKey = (e) => e.key === "Escape" && onClose();
        window.addEventListener("keydown", onKey);
        const prev = document.body.style.overflow;
        document.body.style.overflow = "hidden";
        return () => {
            window.removeEventListener("keydown", onKey);
            document.body.style.overflow = prev;
        };
    }, [onClose]);

    return (
        <motion.div
            className="fixed inset-0 z-50 flex items-end justify-center bg-black/70 p-0 backdrop-blur-sm md:items-center md:p-6"
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            onClick={onClose}
        >
            <motion.div
                role="dialog"
                aria-modal="true"
                aria-label={p.title}
                className="max-h-[88vh] w-full max-w-2xl overflow-y-auto rounded-t-3xl border border-[#23242c] bg-[#0d0d12] p-6 md:rounded-3xl md:p-9"
                initial={{ y: 60, opacity: 0 }}
                animate={{ y: 0, opacity: 1 }}
                exit={{ y: 60, opacity: 0 }}
                transition={{ type: "spring", stiffness: 260, damping: 28 }}
                onClick={(e) => e.stopPropagation()}
            >
                <div className="flex items-start justify-between gap-4">
                    <div>
                        <p className="text-sm text-sig">{p.badge}</p>
                        <h3 className="mt-1 text-2xl font-extrabold tracking-tight md:text-3xl">{p.title}</h3>
                    </div>
                    <button
                        onClick={onClose}
                        aria-label="Close"
                        className="rounded-full border border-[#2b2c36] px-3.5 py-1.5 text-sm text-mute transition-colors hover:border-sig hover:text-ink"
                    >
                        Close
                    </button>
                </div>

                <p className="mt-4 leading-relaxed text-mute">{p.summary}</p>
                <Block title="Key features" items={p.features} />
                <Block title="How it works" items={p.how} ordered />
                <Block title="What I learned" items={p.learned} />

                <div className="mt-6 flex flex-wrap gap-2">
                    {p.tags.map((t) => (
                        <span key={t} className="rounded-full border border-[#23242c] px-3 py-1 text-xs text-ink">
                            {t}
                        </span>
                    ))}
                </div>

                <div className="mt-8 flex flex-wrap gap-3">
                    <a href={p.live} target="_blank" rel="noreferrer" className={btnPrimary}>Live demo</a>
                    <a href={p.github} target="_blank" rel="noreferrer" className={btnGhost}>GitHub</a>
                </div>
                {p.liveNote && <p className="mt-3 text-xs text-mute">{p.liveNote}</p>}
            </motion.div>
        </motion.div>
    );
}

